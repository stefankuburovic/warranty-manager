// Normalize language code
function normalizeLanguage(lang) {
  if (!lang) return 'en';
  // Map various Serbian language codes
  if (lang.startsWith('sr')) {
    // If it's exactly 'sr', default to Latin
    if (lang === 'sr') {
      return 'sr-Latn';
    }
    // Otherwise use as-is (sr-Latn or sr-Cyrl)
    return lang;
  }
  return lang;
}

// Get translations for a specific language, fallback to English
function getTranslations(lang = 'en') {
  const normalizedLang = normalizeLanguage(lang);
  return translations[normalizedLang] || translations.en;
}

// Format date based on locale
function formatDate(date, locale = 'en') {
  const d = new Date(date);
  const normalizedLocale = normalizeLanguage(locale);
  
  if (normalizedLocale === 'sr-Latn' || normalizedLocale === 'sr') {
    return d.toLocaleDateString('sr-Latn-RS', {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit'
    });
  } else if (normalizedLocale === 'sr-Cyrl') {
    return d.toLocaleDateString('sr-RS', {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit'
    });
  }
  return d.toLocaleDateString('en-US', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit'
  });
}

// Format date with full month name
function formatDateLong(date, locale = 'en') {
  const d = new Date(date);
  const normalizedLocale = normalizeLanguage(locale);
  
  if (normalizedLocale === 'sr-Latn' || normalizedLocale === 'sr') {
    return d.toLocaleDateString('sr-Latn-RS', {
      year: 'numeric',
      month: 'long',
      day: 'numeric'
    });
  } else if (normalizedLocale === 'sr-Cyrl') {
    return d.toLocaleDateString('sr-RS', {
      year: 'numeric',
      month: 'long',
      day: 'numeric'
    });
  }
  return d.toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });
}

